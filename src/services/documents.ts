import PDFDocument from "pdfkit";
import type { CaseFile, LostReport, Reminder } from "../domain/case.js";

/** Renders a PDF with pdfkit and resolves with the bytes. */
function render(build: (doc: PDFKit.PDFDocument) => void): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50, info: { Title: "Sarva Rakshak", Author: "Sarva Rakshak" } });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    build(doc);
    doc.end();
  });
}

const rupee = (n: number) => `Rs. ${n.toLocaleString("en-IN")}`; // built-in PDF fonts lack the ₹ glyph

export function buildLostReportPdf(c: CaseFile, r: Omit<LostReport, "pdfBase64">): Promise<Buffer> {
  return render((doc) => {
    doc.fontSize(9).fillColor("#b45309").text("PREPARED DRAFT FOR SUBMISSION - generated by Sarva Rakshak (hackathon prototype). Not an official police record.", { align: "center" });
    doc.moveDown();
    doc.fillColor("#111").fontSize(18).text("Lost Article Report", { align: "center" });
    doc.fontSize(10).text(`Reference: ${r.reference}    Case: ${c.caseId}`, { align: "center" });
    doc.moveDown(1.2);
    const row = (k: string, v: string) => {
      doc.font("Helvetica-Bold").text(`${k}: `, { continued: true }).font("Helvetica").text(v);
    };
    doc.fontSize(11);
    row("Complainant", `${c.user.name}, ${c.user.city}`);
    row("Contact", `${c.user.phoneMasked} / ${c.user.email}`);
    row("Place of loss", r.location);
    row("Approx. time of loss", r.lostAt);
    if (r.station) row("Jurisdiction (nearest station)", `${r.station.name}${r.station.address ? `, ${r.station.address}` : ""}`);
    doc.moveDown();
    doc.font("Helvetica-Bold").text("Articles lost");
    doc.font("Helvetica");
    r.items.forEach((i) => doc.text(`  - ${i}`));
    doc.moveDown();
    doc.font("Helvetica-Bold").text("Statement");
    doc.font("Helvetica").text(r.narrative);
    if (c.cardActions.length) {
      doc.moveDown();
      doc.font("Helvetica-Bold").text("Card blocks already performed");
      doc.font("Helvetica");
      c.cardActions.forEach((a) => doc.text(`  - ${a.bank} card ending ${a.last4}: ${a.status} via ${a.method}, ref ${a.reference}`));
    }
    const flagged = c.flaggedTransactions.filter((t) => t.suspicious);
    if (flagged.length) {
      doc.moveDown();
      doc.font("Helvetica-Bold").text("Suspected fraudulent transactions after the loss");
      doc.font("Helvetica");
      flagged.forEach((t) => doc.text(`  - ${rupee(t.amountInr)} at ${t.merchant} on ${new Date(t.at).toLocaleString("en-IN")} (${t.id})`));
    }
    doc.moveDown(2);
    doc.text("I declare that the information above is true to the best of my knowledge.");
    doc.moveDown(2);
    doc.text("Signature: ____________________        Date: ______________");
  });
}

export function buildCaseFilePdf(c: CaseFile): Promise<Buffer> {
  return render((doc) => {
    doc.fontSize(20).text("Sarva Rakshak - Case File", { align: "center" });
    doc.fontSize(10).text(`Case ${c.caseId} · opened ${new Date(c.createdAt).toLocaleString("en-IN")}`, { align: "center" });
    doc.moveDown();
    const section = (title: string, lines: string[]) => {
      if (!lines.length) return;
      doc.moveDown(0.6).fontSize(13).font("Helvetica-Bold").text(title);
      doc.fontSize(10.5).font("Helvetica");
      lines.forEach((l) => doc.text(`- ${l}`));
    };
    section("Incident", [`Lost: ${c.incident.items.join(", ") || "-"}`, `Where: ${c.incident.location ?? "-"}`, `When: ${c.incident.lostAt ?? "-"}`]);
    section("Cards", c.cardActions.map((a) => `${a.bank} ending ${a.last4}: ${a.status} via ${a.method} (ref ${a.reference})`));
    section("Suspicious transactions", c.flaggedTransactions.filter((t) => t.suspicious).map((t) => `${rupee(t.amountInr)} at ${t.merchant} (${t.id}) - ${t.reason ?? ""}`));
    section("Disputes", c.disputes.map((d) => `${d.disputeId}: ${rupee(d.amountInr)} - ${d.expectedResolution}`));
    if (c.report) section("Police report", [`Reference ${c.report.reference}`, c.report.station ? `Station: ${c.report.station.name}` : "", "Submitted to: simulated police portal (carry the attached PDF to the station)"].filter(Boolean));
    c.reissue.forEach((g) =>
      section(`Reissue: ${g.title}`, [...g.urgentActions.map((u) => `URGENT: ${u}`), ...g.steps, `Portal: ${g.portal}`, `Fee: ${g.indicativeFee.replace("₹", "Rs. ")} · Time: ${g.typicalTime}`]),
    );
    section("Reminders", c.reminders.map((r) => `${r.title} - ${new Date(r.dueAt).toLocaleString("en-IN")}`));
    doc.moveDown().fontSize(8).fillColor("#666").text("Bank and police systems in this prototype are simulated. Location data © OpenStreetMap contributors.");
  });
}

const icsDate = (d: Date) => d.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");
const icsEscape = (s: string) => s.replace(/\\/g, "\\\\").replace(/\n/g, "\\n").replace(/([,;])/g, "\\$1");

export function buildIcs(reminders: Reminder[], now = new Date()): string {
  const lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Sarva Rakshak//EN", "CALSCALE:GREGORIAN", "METHOD:PUBLISH"];
  for (const r of reminders) {
    const start = new Date(r.dueAt);
    const end = new Date(start.getTime() + 30 * 60_000);
    lines.push(
      "BEGIN:VEVENT",
      `UID:${r.id}@sarva-rakshak`,
      `DTSTAMP:${icsDate(now)}`,
      `DTSTART:${icsDate(start)}`,
      `DTEND:${icsDate(end)}`,
      `SUMMARY:${icsEscape(r.title)}`,
      `DESCRIPTION:${icsEscape(r.notes ?? "Follow-up from Sarva Rakshak")}`,
      "BEGIN:VALARM",
      "ACTION:DISPLAY",
      `DESCRIPTION:${icsEscape(r.title)}`,
      "TRIGGER:-PT30M",
      "END:VALARM",
      "END:VEVENT",
    );
  }
  lines.push("END:VCALENDAR");
  return lines.join("\r\n") + "\r\n";
}
